#!/usr/bin/env python3
"""Live proof: run the probe suite against a REAL vision model and write the
evidence artifacts — out/RESULTS.md (scorecard + every raw answer) and
out/vss_results_table.tex (paste-ready for the VSS paper's empty Results
section). Exits non-zero if nothing could be measured. Usage:

    ANTHROPIC_API_KEY=… python run_real.py [--model claude-sonnet-5]
"""
from __future__ import annotations

import argparse
import datetime
import sys
from pathlib import Path

from probe_runner import MockVSS, gate, load_spec, run_probes, scorecard
from vlm_adapter import RealVLM

OUT = Path(__file__).parent / "out"


def latex_table(baseline: dict, real: dict, model: str) -> str:
    rows = []
    for mode_id, b in baseline.items():
        r = real[mode_id]
        rs = "not measured" if not r["measured"] else f"{r['score']:.2f}"
        verdict = "—" if not r["measured"] else ("Pass" if r["score"] >= r["threshold"] else "Fail")
        rows.append(
            f"    {mode_id.replace('_', ' ')} & {b['score']:.2f} & {rs} & "
            f"{r['threshold']:.2f} & {verdict} \\\\"
        )
    body = "\n".join(rows)
    return (
        "% Auto-generated by FM-os skills/vlm-failure-probe/reference/run_real.py\n"
        "% Baseline column = the paper's observed VSS failures encoded as canned answers.\n"
        "\\begin{table}[t]\n  \\centering\n"
        f"  \\caption{{Failure-mode probe scores: observed VSS baseline vs. {model}.}}\n"
        "  \\label{tab:probe-results}\n"
        "  \\begin{tabular}{lcccc}\n"
        "    \\hline\n"
        f"    Failure mode & VSS (obs.) & {model} & Min & Verdict \\\\\n"
        "    \\hline\n"
        f"{body}\n"
        "    \\hline\n  \\end{tabular}\n\\end{table}\n"
    )


def results_md(baseline: dict, real: dict, spec: dict, model: str, stamp: str) -> str:
    ok, reasons = gate(real, spec)
    lines = [
        "# vlm-failure-probe — live run against a real VLM",
        "",
        f"- **model**: `{model}` (Anthropic Messages API, {stamp})",
        "- **stimuli**: deterministic synthetic frames (`stimuli.py`), the paper's own methodology",
        "- **baseline**: the VSS paper's observed failures, canned verbatim (`MockVSS`)",
        "",
        "| failure mode | VSS baseline | real VLM | min | verdict |",
        "|---|---|---|---|---|",
    ]
    for mode_id, b in baseline.items():
        r = real[mode_id]
        rs = "not measured" if not r["measured"] else f"{r['score']:.2f}"
        verdict = "—" if not r["measured"] else ("✅ pass" if r["score"] >= r["threshold"] else "❌ fail")
        lines.append(f"| {mode_id} | {b['score']:.2f} | {rs} | {r['threshold']:.2f} | {verdict} |")
    lines += ["", f"**Gate:** {'PASS' if ok else 'FAIL — ' + '; '.join(reasons)}", "", "## Raw answers (evidence)", ""]
    for mode_id, r in real.items():
        lines.append(f"### {mode_id}")
        for p in r["probes"]:
            ans = p["answer"] if p["answer"] is not None else "*(not measured)*"
            sc = "—" if p["score"] is None else f"{p['score']:.2f}"
            lines.append(f"- `{p['id']}` [{sc}] {ans}")
        lines.append("")
    return "\n".join(lines)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", default=None)
    args = ap.parse_args()

    spec = load_spec()
    model = args.model or RealVLM().model
    real_model = RealVLM(model) if args.model else RealVLM()
    print(f"probing {model} across {sum(len(m['probes']) for m in spec['failure_modes'])} probes…")
    real = run_probes(real_model, spec)
    baseline = run_probes(MockVSS(), spec)

    print(scorecard(f"real VLM ({model})", real, spec))
    if not any(r["measured"] for r in real.values()):
        print("nothing measured (no ANTHROPIC_API_KEY?) — no artifacts written")
        sys.exit(1)

    stamp = datetime.date.today().isoformat()
    OUT.mkdir(exist_ok=True)
    (OUT / "RESULTS.md").write_text(results_md(baseline, real, spec, model, stamp))
    (OUT / "vss_results_table.tex").write_text(latex_table(baseline, real, model))
    print(f"wrote {OUT / 'RESULTS.md'} and {OUT / 'vss_results_table.tex'}")
